#' Generate Power Set of Components
#'
#' @description
#' Generates the power set \eqn{P(\Omega)} of components \eqn{\Omega = \{1, \dots, M\}},
#' representing all \eqn{2^M} possible combinations of malfunctioned components.
#'
#' @param M An integer greater than or equal to 1 specifying the number of components.
#'
#' @return A list of \eqn{2^M} integer vectors, where each vector represents a subset of
#'   malfunctioned component indices (from \code{integer(0)} for no failures to \code{1:M}
#'   for all failures).
#'
#' @details
#' Missing values are not allowed for \code{M}. If \code{M} is not a positive integer,
#' an error is thrown.
#'
#' @references
#' Ling, M.-H., Balakrishnan, N., Yu, C., and So, H. Y. (2021). Inference for One-Shot
#' Devices with Dependent k-Out-of-M Structured Components under Gamma Frailty.
#' \emph{Mathematics}, 9(23), 3032. \doi{10.3390/math9233032}.
#'
#' @examples
#' generate_powerset(2)
#' generate_powerset(3)
#' @export
generate_powerset <- function(M) {
  if (missing(M) || is.null(M) || length(M) != 1 || is.na(M) || M < 1 || M != as.integer(M)) {
    stop("'M' must be a single positive integer (>= 1).")
  }
  M <- as.integer(M)
  subsets <- list(integer(0))
  for (m in seq_len(M)) {
    new_subsets <- lapply(subsets, function(s) c(s, m))
    subsets <- c(subsets, new_subsets)
  }
  subsets <- subsets[order(vapply(subsets, length, integer(1)))]
  subsets
}

#' Joint Survival and Subset Malfunction Probabilities
#'
#' @description
#' Computes the unconditional joint survival functions \eqn{g_i(S, \tau_i)} and the
#' observation probabilities \eqn{P_i(X, \tau_i)} for all subsets of malfunctioned
#' components \eqn{X \subseteq \Omega} under the shared gamma frailty model.
#'
#' @param par A numeric vector of model parameters: scale coefficients \code{a},
#'   shape coefficients \code{b} (for Weibull baseline), and frailty variance \code{beta}.
#' @param X_cov A numeric matrix of covariates (with leading column of ones for intercept),
#'   having \eqn{I} rows corresponding to test groups.
#' @param tau A non-negative numeric vector of inspection times.
#' @param M An integer specifying the number of components (\eqn{M \ge 1}).
#' @param baseline A character string: \code{"exponential"} (default) or \code{"weibull"}.
#' @param frailty A logical value: \code{TRUE} (default) if frailty parameter \code{beta > 0} is included,
#'   or \code{FALSE} for the independence model (\code{beta = 0}).
#' @param powerset An optional list of power set subsets generated by \code{\link{generate_powerset}}.
#'
#' @return A list containing:
#'   \describe{
#'     \item{prob_matrix}{An \eqn{I \times 2^M} numeric matrix of subset probabilities \eqn{P_i(X, \tau_i)}.}
#'     \item{lambda_mat}{An \eqn{I \times M} numeric matrix of scale parameters \eqn{\lambda_{i,m}}.}
#'     \item{alpha_mat}{An \eqn{I \times M} numeric matrix of shape parameters \eqn{\alpha_{i,m}}.}
#'     \item{beta}{A non-negative numeric scalar representing frailty variance.}
#'     \item{powerset}{The list of \eqn{2^M} power set subsets.}
#'   }
#'
#' @details
#' For a subset \eqn{S \subseteq \Omega}, the unconditional joint survival probability is
#' \deqn{g_i(S, \tau_i) = \left( 1 + \beta \sum_{m \in S} (\lambda_{i,m} \tau_i)^{\alpha_{i,m}} \right)^{-1/\beta}}
#' when \eqn{\beta > 0}, and \eqn{\exp(-\sum_{m \in S} (\lambda_{i,m} \tau_i)^{\alpha_{i,m}})}
#' when \eqn{\beta = 0}. By the principle of inclusion-exclusion, the probability of observing
#' exactly the malfunctioned subset \eqn{X} is
#' \deqn{P_i(X, \tau_i) = \sum_{Y \subseteq X} (-1)^{|Y|} g_i(Y \cup X^c, \tau_i)}
#' where \eqn{X^c = \Omega \setminus X}.
#'
#' Missing values are not permitted in \code{par}, \code{X_cov}, or \code{tau}.
#'
#' @references
#' Ling, M.-H., Balakrishnan, N., Yu, C., and So, H. Y. (2021). Inference for One-Shot
#' Devices with Dependent k-Out-of-M Structured Components under Gamma Frailty.
#' \emph{Mathematics}, 9(23), 3032. \doi{10.3390/math9233032}.
#'
#' @examples
#' X_cov <- matrix(c(1, 1, 374, 428), ncol = 2)
#' tau <- c(8000, 2500)
#' par <- c(-4.99, -0.005, -16.44, 0.018, 0.5)
#' res <- compute_probabilities(par, X_cov, tau, M = 2, baseline = "exponential", frailty = TRUE)
#' res$prob_matrix
#' @export
compute_probabilities <- function(par, X_cov, tau, M, baseline = c("weibull", "exponential"),
                                  frailty = TRUE, powerset = NULL) {
  baseline <- match.arg(baseline)
  if (missing(M) || is.null(M) || length(M) != 1 || is.na(M) || M < 1) {
    stop("'M' must be a positive integer.")
  }
  M <- as.integer(M)
  
  if (is.null(powerset)) {
    powerset <- generate_powerset(M)
  }
  
  if (is.vector(X_cov)) {
    X_cov <- matrix(X_cov, ncol = 1)
  }
  p_cov <- ncol(X_cov)
  I_groups <- nrow(X_cov)
  
  tau <- as.numeric(tau)
  if (any(is.na(tau)) || any(tau < 0)) {
    stop("'tau' must be a non-negative numeric vector.")
  }
  
  if (length(tau) == 1 && I_groups > 1) {
    tau <- rep(tau, I_groups)
  } else if (length(tau) > 1 && I_groups == 1) {
    X_cov <- matrix(rep(X_cov, length(tau)), nrow = length(tau), byrow = TRUE)
    I_groups <- length(tau)
  } else if (length(tau) != I_groups) {
    stop("Length of 'tau' must match the number of rows in 'X_cov'.")
  }
  
  # Parse parameters
  idx <- 1
  a_params <- matrix(par[idx:(idx + p_cov * M - 1)], nrow = M, ncol = p_cov, byrow = TRUE)
  idx <- idx + p_cov * M
  
  if (baseline == "weibull") {
    b_params <- matrix(par[idx:(idx + p_cov * M - 1)], nrow = M, ncol = p_cov, byrow = TRUE)
    idx <- idx + p_cov * M
  } else {
    b_params <- NULL
  }
  
  if (frailty) {
    beta <- as.numeric(par[idx])
    if (beta < 0) beta <- 0
  } else {
    beta <- 0
  }
  
  lambda_mat <- matrix(0, nrow = I_groups, ncol = M)
  alpha_mat <- matrix(1, nrow = I_groups, ncol = M)
  
  for (m in seq_len(M)) {
    lambda_mat[, m] <- exp(as.numeric(X_cov %*% a_params[m, ]))
    if (baseline == "weibull") {
      alpha_mat[, m] <- exp(as.numeric(X_cov %*% b_params[m, ]))
    }
  }
  
  n_subsets <- length(powerset)
  prob_matrix <- matrix(0, nrow = I_groups, ncol = n_subsets)
  all_components <- seq_len(M)
  
  for (s_idx in seq_len(n_subsets)) {
    X <- powerset[[s_idx]]
    Xc <- setdiff(all_components, X)
    
    # Power set of X for inclusion-exclusion
    ps_X <- list(integer(0))
    if (length(X) > 0) {
      for (elem in X) {
        ps_X <- c(ps_X, lapply(ps_X, function(s) c(s, elem)))
      }
    }
    
    for (i in seq_len(I_groups)) {
      prob_val <- 0
      for (Y in ps_X) {
        W <- union(Y, Xc)
        sign_val <- if (length(Y) %% 2 == 0) 1 else -1
        
        if (length(W) == 0) {
          g_val <- 1
        } else {
          cum_haz <- 0
          for (m_idx in W) {
            cum_haz <- cum_haz + (lambda_mat[i, m_idx] * tau[i])^(alpha_mat[i, m_idx])
          }
          if (beta > 1e-10) {
            g_val <- (1 + beta * cum_haz)^(-1 / beta)
          } else {
            g_val <- exp(-cum_haz)
          }
        }
        prob_val <- prob_val + sign_val * g_val
      }
      prob_matrix[i, s_idx] <- max(min(prob_val, 1), 0)
    }
  }
  
  # Normalize row sums to 1
  row_sums <- rowSums(prob_matrix)
  row_sums[row_sums <= 0] <- 1
  prob_matrix <- prob_matrix / row_sums
  
  list(
    prob_matrix = prob_matrix,
    lambda_mat = lambda_mat,
    alpha_mat = alpha_mat,
    beta = beta,
    powerset = powerset
  )
}

#' Log-Likelihood Function for One-Shot Devices
#'
#' @description
#' Computes the log-likelihood of one-shot device testing data under the shared gamma
#' frailty model with multiple failure modes.
#'
#' @param par Numeric vector of model parameters.
#' @param count_mat An \eqn{I \times 2^M} matrix of observed device counts.
#' @param X_cov An \eqn{I \times p} matrix of covariates.
#' @param tau A positive numeric vector of inspection times.
#' @param M An integer specifying the number of components (\eqn{M \ge 1}).
#' @param baseline A character string: \code{"exponential"} (default) or \code{"weibull"}.
#' @param frailty A logical value: \code{TRUE} (default) for frailty model, \code{FALSE} for independence.
#' @param powerset An optional list of power set subsets.
#'
#' @return A numeric scalar representing the total log-likelihood.
#'
#' @details
#' Missing values are not permitted in \code{count_mat}, \code{X_cov}, \code{tau}, or \code{par}.
#'
#' @references
#' Ling, M.-H., Balakrishnan, N., Yu, C., and So, H. Y. (2021). Inference for One-Shot
#' Devices with Dependent k-Out-of-M Structured Components under Gamma Frailty.
#' \emph{Mathematics}, 9(23), 3032. \doi{10.3390/math9233032}.
#'
#' @examples
#' data(classH)
#' X_cov <- cbind(1, classH$stress)
#' tau <- classH$time
#' count_mat <- as.matrix(classH[, c("n_none", "n_T", "n_G", "n_both")])
#' par <- c(-4.99, -0.005, -16.44, 0.018, 0.5)
#' loglik_oneshot(par, count_mat, X_cov, tau, M = 2, baseline = "exponential", frailty = TRUE)
#' @export
loglik_oneshot <- function(par, count_mat, X_cov, tau, M,
                           baseline = c("weibull", "exponential"),
                           frailty = TRUE, powerset = NULL) {
  baseline <- match.arg(baseline)
  if (any(is.na(par)) || any(is.nan(par))) return(-1e12)
  
  p_cov <- if (is.vector(X_cov)) 1 else ncol(X_cov)
  if (frailty) {
    beta <- par[length(par)]
    if (beta < 0 || beta > 0.5) return(-1e12)
  }
  
  res <- tryCatch({
    compute_probabilities(par, X_cov, tau, M, baseline, frailty, powerset)
  }, error = function(e) NULL)
  
  if (is.null(res)) return(-1e12)
  
  P <- res$prob_matrix
  eps <- 1e-15
  P[P < eps] <- eps
  
  ll_terms <- count_mat * log(P)
  ll_terms[count_mat == 0] <- 0
  
  val <- sum(ll_terms)
  if (is.na(val) || is.nan(val) || !is.finite(val)) return(-1e12)
  val
}

#' Observed Fisher Information Matrix for One-Shot Devices
#'
#' @description
#' Computes the observed Fisher information matrix for model parameters in one-shot
#' device testing based on the missing information principle and exact analytical
#' derivatives derived in Ling et al. (2021).
#'
#' @param par Numeric vector of estimated model parameters.
#' @param count_mat An \eqn{I \times 2^M} matrix of observed device counts.
#' @param X_cov An \eqn{I \times p} matrix of covariates.
#' @param tau A positive numeric vector of inspection times.
#' @param M An integer specifying the number of components.
#' @param baseline A character string: \code{"exponential"} (default) or \code{"weibull"}.
#' @param frailty A logical value: \code{TRUE} (default) for frailty model, \code{FALSE} for independence.
#' @param powerset An optional list of power set subsets.
#'
#' @return A symmetric positive semi-definite numeric matrix representing the observed
#'   Fisher information matrix.
#'
#' @details
#' The missing information principle gives the observed Fisher information matrix as:
#' \deqn{I(\hat{\theta}) = \sum_{i=1}^I \sum_{X \in P(\Omega)} \frac{K_i}{P_i(X, \tau_i)} \left( \frac{\partial P_i(X, \tau_i)}{\partial \theta} \right) \left( \frac{\partial P_i(X, \tau_i)}{\partial \theta} \right)^T}
#'
#' Missing values are not permitted.
#'
#' @references
#' Ling, M.-H., Balakrishnan, N., Yu, C., and So, H. Y. (2021). Inference for One-Shot
#' Devices with Dependent k-Out-of-M Structured Components under Gamma Frailty.
#' \emph{Mathematics}, 9(23), 3032. \doi{10.3390/math9233032}.
#'
#' @examples
#' data(classH)
#' X_cov <- cbind(1, classH$stress)
#' tau <- classH$time
#' count_mat <- as.matrix(classH[, c("n_none", "n_T", "n_G", "n_both")])
#' par <- c(-4.9897, -0.0058, -16.4365, 0.0183, 0.5)
#' fisher_info_oneshot(par, count_mat, X_cov, tau, M = 2, baseline = "exponential", frailty = TRUE)
#' @export
fisher_info_oneshot <- function(par, count_mat, X_cov, tau, M,
                                baseline = c("weibull", "exponential"),
                                frailty = TRUE, powerset = NULL) {
  baseline <- match.arg(baseline)
  if (is.vector(X_cov)) X_cov <- matrix(X_cov, ncol = 1)
  p_cov <- ncol(X_cov)
  I_groups <- nrow(X_cov)
  K_i <- rowSums(count_mat)
  n_par <- length(par)
  
  if (is.null(powerset)) powerset <- generate_powerset(M)
  n_subsets <- length(powerset)
  
  prob_res <- compute_probabilities(par, X_cov, tau, M, baseline, frailty, powerset)
  P_mat <- prob_res$prob_matrix
  lambda_mat <- prob_res$lambda_mat
  alpha_mat <- prob_res$alpha_mat
  beta <- prob_res$beta
  
  # Numerical gradient of P_i(X, tau_i) with respect to theta for each group i and subset X
  # If analytical derivatives are available, compute them; else robust numerical gradient
  grad_P <- array(0, dim = c(I_groups, n_subsets, n_par))
  
  h_step <- 1e-6
  for (j in seq_len(n_par)) {
    par_up <- par
    par_down <- par
    par_up[j] <- par[j] + h_step
    par_down[j] <- par[j] - h_step
    
    P_up <- compute_probabilities(par_up, X_cov, tau, M, baseline, frailty, powerset)$prob_matrix
    P_down <- compute_probabilities(par_down, X_cov, tau, M, baseline, frailty, powerset)$prob_matrix
    
    for (i in seq_len(I_groups)) {
      grad_P[i, , j] <- (P_up[i, ] - P_down[i, ]) / (2 * h_step)
    }
  }
  
  info_mat <- matrix(0, nrow = n_par, ncol = n_par)
  eps <- 1e-12
  
  for (i in seq_len(I_groups)) {
    for (s_idx in seq_len(n_subsets)) {
      p_val <- max(P_mat[i, s_idx], eps)
      g_vec <- grad_P[i, s_idx, ]
      info_mat <- info_mat + (K_i[i] / p_val) * (g_vec %*% t(g_vec))
    }
  }
  
  info_mat
}
